#Implement a Python program to perform list operations (insert, append, remove, sort, reverse)

# Create a list
my_list = [30, 10, 50, 20]

print("Original list:", my_list)

# Append
my_list.append(40)
print("After append:", my_list)

# Insert
my_list.insert(1, 15)
print("After insert:", my_list)

# Remove
my_list.remove(30)
print("After remove:", my_list)

# Sort
my_list.sort()
print("After sort:", my_list)

# Reverse
my_list.reverse()
print("After reverse:", my_list)