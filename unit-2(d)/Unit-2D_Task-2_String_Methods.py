#Implement a Python program to demonstrate string methods (upper, lower, strip, split, join, replace, find)

s = "  Hello Python Programming  "

print("Original String:", s)
print("Uppercase:", s.upper())
print("Lowercase:", s.lower())
print("Strip:", s.strip())
print("Split:", s.split())
print("Join:", "-".join(["Hello", "Python"]))
print("Replace:", s.replace("Python", "Java"))
print("Find:", s.find("Python"))